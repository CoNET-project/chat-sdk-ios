#if BEAMIO_TEST_HOOKS
import XCTest
@testable import ConetChatSDK

/// The identity judgement of the same key. The primary-fingerprint branch runs only with public
/// keys that can be read, so these cases use real PGP test keys generated at test time with the native layer. The
/// fallback to the key ID runs when a public armor cannot be read. The private armor is held in memory for these tests only; the identity never reads it.
final class PGPIdentityJudgementTests: XCTestCase {
	private let alice = "0xA11CE00000000000000000000000000000000001"
	private let route = "-----BEGIN PGP PUBLIC KEY BLOCK-----\nsynthetic-route\n-----END PGP PUBLIC KEY BLOCK-----"

	/// Two generated test key pairs, made once per test run.
	private enum GeneratedKeys {
		static var pairs: [(privateArmor: String, publicArmor: String)] = []
	}

	override func setUp() {
		super.setUp()
		BeamioChatPgpKeychain.memory = BeamioChatPgpKeychain.MemoryRecords()
	}

	override func tearDown() {
		BeamioChatPgpKeychain.memory = nil
		super.tearDown()
	}

	/// Two real PGP test keys, generated by the native layer at test time (not a user or QA key).
	private func generatedKeys() throws -> [(privateArmor: String, publicArmor: String)] {
		// The macOS SwiftPM test host has no X-19: key generation answers pgp_native_pending. Skipped there, run where X-19 is linked (the iOS simulator / an app host). The native PGP
		// path of these cases is not exercised on macOS: it is a coverage gap listed for the device/app-host run.
		try XCTSkipUnless(BeamioPGPNative.linked, "X-19 is not linked in this build (macOS test build); the iOS simulator runs this case")
		if GeneratedKeys.pairs.isEmpty {
			for label in ["first", "second"] {
				let pair = try BeamioPGPNative.generateKeyPair(name: "Beamio identity judgement test \(label)").get()
				GeneratedKeys.pairs.append(pair)
			}
		}
		return GeneratedKeys.pairs
	}

	private func save(privateArmor: String, publicArmor: String, keyId: String) {
		XCTAssertTrue(BeamioChatPgpKeychain.save(BeamioChatPgpKeychain.Secrets(
			privateKeyArmor: privateArmor, publicKeyArmor: publicArmor, pgpKeyId: keyId,
			routePublicKeyArmor: route, entryDomains: [], siNodes: [], mailboxIp: "", eoa: alice)))
	}

	private func restore(privateArmor: String, publicArmor: String, keyId: String) -> (code: String, state: String) {
		BeamioPGPRestoreCommands.writeLocal(eoa: alice, evaluation: BeamioPGPRestoreCommands.Evaluation(
			state: "ok", failureClass: nil, code: nil, offerEntry: false, uiKey: nil,
			armor: privateArmor, chainPublicArmor: publicArmor, chainSubkeyKeyID: keyId, restoredSubkeyKeyID: keyId))
	}

	/// The same primary fingerprint with another armor text (line endings changed): the identity is the same, so already_exists, and nothing changes.
	func testTheSameFingerprintWithAnotherArmorTextIsAlreadyExists() throws {
		let first = try generatedKeys()[0]
		let stored = try XCTUnwrap(BeamioPGPBackup.keyIdentity(armor: first.publicArmor), "the generated key is readable")
		let reformatted = first.publicArmor.replacingOccurrences(of: "\n", with: "\r\n")
		XCTAssertNotEqual(reformatted, first.publicArmor, "the armor text differs")
		let candidate = try XCTUnwrap(BeamioPGPBackup.keyIdentity(armor: reformatted), "the reformatted armor is still readable")
		XCTAssertEqual(candidate.fingerprint, stored.fingerprint, "the precondition: the primary fingerprint is the same")
		save(privateArmor: first.privateArmor, publicArmor: first.publicArmor, keyId: stored.subkeyKeyID)
		let before = BeamioChatPgpKeychain.scopedSnapshot(eoa: alice)

		let result = restore(privateArmor: first.privateArmor, publicArmor: reformatted, keyId: candidate.subkeyKeyID)

		XCTAssertEqual(result.code, "already_exists", "the primary fingerprint decides, not the armor text")
		XCTAssertEqual(result.state, "ok")
		XCTAssertEqual(BeamioChatPgpKeychain.scopedSnapshot(eoa: alice), before, "nothing is written")
	}

	/// The same key ID with another primary fingerprint is another key: not_ready, and nothing is written.
	func testTheSameKeyIdWithAnotherPrimaryFingerprintIsNotReady() throws {
		let keys = try generatedKeys()
		let first = try XCTUnwrap(BeamioPGPBackup.keyIdentity(armor: keys[0].publicArmor))
		let second = try XCTUnwrap(BeamioPGPBackup.keyIdentity(armor: keys[1].publicArmor))
		XCTAssertNotEqual(second.fingerprint, first.fingerprint, "the precondition: the two keys differ")
		save(privateArmor: keys[0].privateArmor, publicArmor: keys[0].publicArmor, keyId: first.subkeyKeyID)
		let before = BeamioChatPgpKeychain.scopedSnapshot(eoa: alice)

		let result = restore(privateArmor: keys[1].privateArmor, publicArmor: keys[1].publicArmor, keyId: first.subkeyKeyID)

		XCTAssertEqual(result.code, "not_ready", "the primary fingerprints differ, so the identity differs")
		XCTAssertEqual(result.state, "undetermined")
		XCTAssertEqual(BeamioChatPgpKeychain.scopedSnapshot(eoa: alice), before, "nothing is written")
	}

	/// A public armor that cannot be read: the identity falls back to the key ID. The same key ID is already_exists; another key ID is not_ready.
	func testAnUnreadableArmorFallsBackToTheKeyId() throws {
		let key = try generatedKeys()[0]
		XCTAssertNil(BeamioPGPBackup.keyIdentity(armor: "not-a-key"), "the precondition: the armor cannot be read")
		save(privateArmor: key.privateArmor, publicArmor: "not-a-key", keyId: "KEY-1")
		let before = BeamioChatPgpKeychain.scopedSnapshot(eoa: alice)

		XCTAssertEqual(restore(privateArmor: key.privateArmor, publicArmor: "not-a-key-either", keyId: "KEY-1").code, "already_exists",
		               "the same key ID is the same identity when the fingerprint cannot be read")
		XCTAssertEqual(BeamioChatPgpKeychain.scopedSnapshot(eoa: alice), before, "nothing is written")
		XCTAssertEqual(restore(privateArmor: key.privateArmor, publicArmor: "not-a-key", keyId: "KEY-2").code, "not_ready",
		               "another key ID is another identity")
		XCTAssertEqual(BeamioChatPgpKeychain.scopedSnapshot(eoa: alice), before, "nothing is written")
	}
}
#endif
